def web_traffic(seed: int = 17) -> pd.Series:
    """Daily visits to a product website over three years.

    Planted effects: steady growth, a strong weekday/weekend pattern, a
    yearly cycle (quiet in late December), a product launch on 2024-09-10
    that permanently lifts traffic ~25%, and a 3-day outage with missing data.
    """
    rng = np.random.default_rng(seed)
    dates = pd.date_range("2022-07-01", "2025-06-30", freq="D")
    t = np.arange(len(dates))
    trend = 20000 * (1 + 0.0006) ** t
    weekly = np.array([1.08, 1.12, 1.10, 1.06, 0.98, 0.78, 0.74])[dates.dayofweek]
    yearly = 1 + 0.10 * np.cos(2 * np.pi * (dates.dayofyear - 80) / 365.25)
    holiday = np.where((dates.month == 12) & (dates.day >= 22), 0.65, 1.0)
    launch = np.where(dates >= "2024-09-10", 1.25, 1.0)
    visits = trend * weekly * yearly * holiday * launch * rng.lognormal(0, 0.05, len(dates))
    series = pd.Series(visits.round(), index=dates, name="visits")
    series.loc["2023-04-11":"2023-04-13"] = np.nan
    return series


def server_metrics(seed: int = 23):
    """Two weeks of per-minute API latency for one service.

    Returns (metrics, true_anomaly) where true_anomaly marks the incidents we
    planted: short slowdowns, one slow memory-leak style drift, and a step up
    after a bad deploy. There are also harmless one-minute blips (like
    garbage-collection pauses) that are NOT incidents: nobody should be
    paged for them, and they're the classic source of false alarms.
    """
    rng = np.random.default_rng(seed)
    idx = pd.date_range("2025-03-01", periods=14 * 24 * 60, freq="min")
    minute_of_day = np.asarray(idx.hour * 60 + idx.minute)
    daily = 1 + 0.6 * np.clip(np.sin(2 * np.pi * (minute_of_day - 7 * 60) / 1440), 0, None)
    latency = 110 * daily * rng.lognormal(0, 0.10, len(idx))
    anomaly = np.zeros(len(idx), dtype=bool)

    blips = rng.choice(len(idx), 14 * 8, replace=False)
    latency[blips] *= rng.uniform(1.8, 3.0, len(blips))

    for start in rng.choice(np.arange(4 * 1440, len(idx) - 500), 10, replace=False):
        width = rng.integers(6, 25)
        latency[start:start + width] *= rng.uniform(1.6, 2.6)
        anomaly[start:start + width] = True

    drift_start, drift_end = 6 * 1440 + 2 * 60, 6 * 1440 + 12 * 60
    latency[drift_start:drift_end] *= np.linspace(1, 1.8, drift_end - drift_start)
    anomaly[drift_start + 150:drift_end] = True

    shift_start = 10 * 1440 + 13 * 60
    latency[shift_start:shift_start + 240] *= 1.45
    anomaly[shift_start:shift_start + 240] = True

    metrics = pd.DataFrame({"latency_ms": latency.round(1)}, index=idx)
    return metrics, pd.Series(anomaly, index=idx, name="true_anomaly")
